import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Build-time only (scripts and tests). Runtime code reads prompts.generated.ts. */
export const agentsDir = join(dirname(fileURLToPath(import.meta.url)), '../../../agents');

export const promptFiles = [
  'listing-parser',
  'moves-tracker',
  'mandate-builder',
  'profile-interviewer',
  'matcher',
] as const;

export function readPromptSources(): Record<string, string> {
  const files: Record<string, string> = {
    voice: readFileSync(join(agentsDir, '_shared/voice.md'), 'utf8'),
  };
  for (const name of promptFiles)
    files[name] = readFileSync(join(agentsDir, name, 'prompt.md'), 'utf8');
  return files;
}

export function renderGenerated(): string {
  return [
    '// Generated by scripts/gen-prompts.ts from agents/**/prompt.md. Do not edit by hand.',
    `export const promptSources: Record<string, string> = ${JSON.stringify(readPromptSources(), null, 2)};`,
    '',
  ].join('\n');
}
